export function glyphRows(ch) {
  const key = ch.toUpperCase();
  const packed = G[key];
  if (!packed) throw new Error(`glyph thieu trong font: ${JSON.stringify(ch)}`);
  return packed.split('/').map((r) => {
    if (r.length !== GW) throw new Error(`glyph ${key} co hang dai ${r.length}, phai bang ${GW}`);
    return r;
  });
}

// Tra ve { rows, width } : mang 7 xuat tu cac chuoi '1'/'0', ghep glyph cach nhau 1 cot.
export function textToRows(text, { tracking = 1 } = {}) {
  const rows = Array.from({ length: GH }, () => '');
  for (const ch of text) {
    const g = glyphRows(ch);
    for (let y = 0; y < GH; y++) rows[y] += g[y] + '0'.repeat(tracking);
  }
  return { rows, width: rows[0].length };
}

